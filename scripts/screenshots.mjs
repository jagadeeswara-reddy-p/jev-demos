import { chromium } from "playwright";
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await page.goto("http://localhost:5317/");
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/1-idle.png`, fullPage: true });
await page.getByRole("button", { name: "8×" }).click();
await page.getByRole("button", { name: "Start run" }).click();
await page.waitForTimeout(5000);
await page.screenshot({ path: `${out}/2-running.png` });
await page.waitForFunction(() => document.body.innerText.includes("Results"), null, { timeout: 120000 });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/3-finished.png`, fullPage: true });
const m = await browser.newPage({ viewport: { width: 390, height: 900 }, deviceScaleFactor: 2 });
await m.goto("http://localhost:5317/");
await m.waitForTimeout(500);
await m.screenshot({ path: `${out}/4-mobile.png`, fullPage: true });
console.log("errors:", errors.length ? errors.join("\n") : "none");
await browser.close();

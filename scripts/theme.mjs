// Checks the theme toggle: bun scripts/theme.mjs <out-dir>
import { chromium } from "playwright";
const out = process.argv[2] ?? ".";
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: "light" });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
await page.goto("http://localhost:5317/");
await page.waitForTimeout(800);
await page.getByRole("button", { name: "Dark", exact: true }).click();
await page.selectOption("#scenario", "linkedin");
await page.getByRole("button", { name: "8×" }).click();
await page.getByRole("button", { name: "Start run" }).click();
await page.waitForTimeout(9000);
await page.getByRole("button", { name: "Pause" }).click();
await page.screenshot({ path: `${out}/theme-dark.png`, fullPage: true });
await page.reload();
await page.waitForTimeout(800);
console.log("after reload data-theme =", await page.evaluate(() => document.documentElement.dataset.theme));
await page.getByRole("button", { name: "System", exact: true }).click();
console.log("system data-theme =", await page.evaluate(() => document.documentElement.dataset.theme ?? "(none)"));
await page.screenshot({ path: `${out}/theme-system-light.png` });
console.log("errors:", errors.length ? errors.join("\n") : "none");
await browser.close();
